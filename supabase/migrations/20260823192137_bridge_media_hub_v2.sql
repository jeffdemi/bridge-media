create function public.idea_organization(target_id uuid) returns uuid language sql stable security definer set search_path = '' as $$
  select c.organization_id from public.ideas i join public.campaigns c on c.id = i.campaign_id where i.id = target_id
$$;
create function public.item_organization(target_id uuid) returns uuid language sql stable security definer set search_path = '' as $$
  select c.organization_id from public.content_items ci join public.content_packages cp on cp.id = ci.package_id join public.ideas i on i.id = cp.idea_id join public.campaigns c on c.id = i.campaign_id where ci.id = target_id
$$;
create function public.has_app_role(target_org uuid, allowed public.app_role[]) returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.user_roles r where r.organization_id = target_org and r.profile_id = (select auth.uid()) and r.role = any(allowed))
$$;

revoke all on function public.idea_organization(uuid), public.item_organization(uuid), public.has_app_role(uuid, public.app_role[]) from public, anon;
grant execute on function public.idea_organization(uuid), public.item_organization(uuid), public.has_app_role(uuid, public.app_role[]) to authenticated;
grant execute on function public.item_organization(uuid) to anon;

