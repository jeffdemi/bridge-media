-- Bridge Media Hub V2: idea development, packages, approval, and public sharing.
create type public.app_role as enum ('contributor', 'media_team', 'approver', 'admin');
create type public.workflow_status as enum ('idea', 'developing', 'draft', 'review', 'approved', 'ready_to_share', 'archived');
create type public.share_event_type as enum ('view', 'caption_copy', 'media_download', 'share');

drop table if exists public.results cascade;
drop table if exists public.assignments cascade;
drop table if exists public.media_assets cascade;
drop table if exists public.content_platforms cascade;
drop table if exists public.content_items cascade;
drop type if exists public.content_status;

alter table public.campaigns add column if not exists is_active boolean not null default true;

create table public.user_roles (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  role public.app_role not null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (organization_id, profile_id, role)
);

create table public.campaign_themes (
  id uuid primary key default extensions.gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  parent_id uuid references public.campaign_themes(id) on delete set null,
  name text not null check (length(trim(name)) between 1 and 120),
  description text not null default '',
  sort_order smallint not null default 0,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (campaign_id, name)
);

create table public.content_types (
  id smallint generated by default as identity primary key,
  key text not null unique check (key ~ '^[a-z0-9_]+$'),
  name text not null unique,
  is_active boolean not null default true,
  sort_order smallint not null unique
);

create table public.ideas (
  id uuid primary key default extensions.gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  theme_id uuid references public.campaign_themes(id) on delete set null,
  title text not null check (length(trim(title)) between 1 and 200),
  description text not null check (length(trim(description)) > 0),
  notes text not null default '',
  status public.workflow_status not null default 'idea',
  owner_id uuid references public.profiles(id) on delete set null,
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ideas_status_valid check (status in ('idea', 'developing', 'draft', 'archived'))
);

create table public.idea_platforms (
  idea_id uuid not null references public.ideas(id) on delete cascade,
  platform_id smallint not null references public.platforms(id) on delete restrict,
  primary key (idea_id, platform_id)
);

create table public.content_packages (
  id uuid primary key default extensions.gen_random_uuid(),
  idea_id uuid not null references public.ideas(id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 200),
  description text not null default '',
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.content_items (
  id uuid primary key default extensions.gen_random_uuid(),
  package_id uuid not null references public.content_packages(id) on delete cascade,
  content_type_id smallint not null references public.content_types(id) on delete restrict,
  theme_id uuid references public.campaign_themes(id) on delete set null,
  title text not null check (length(trim(title)) between 1 and 200),
  body text not null default '',
  caption text not null default '',
  call_to_action text not null default '',
  status public.workflow_status not null default 'draft',
  created_by uuid not null references public.profiles(id) on delete restrict,
  approved_by uuid references public.profiles(id) on delete set null,
  approved_at timestamptz,
  ready_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_item_status_valid check (status in ('draft','review','approved','ready_to_share','archived')),
  constraint approval_fields_valid check (status not in ('approved','ready_to_share') or (approved_by is not null and approved_at is not null)),
  constraint ready_fields_valid check (status <> 'ready_to_share' or ready_at is not null)
);

create table public.content_platforms (
  content_item_id uuid not null references public.content_items(id) on delete cascade,
  platform_id smallint not null references public.platforms(id) on delete restrict,
  platform_caption text not null default '',
  primary key (content_item_id, platform_id)
);

create table public.media_assets (
  id uuid primary key default extensions.gen_random_uuid(),
  content_item_id uuid not null references public.content_items(id) on delete cascade,
  storage_path text not null unique check (storage_path !~ '(^|/)\.\.?(/|$)'),
  file_name text not null check (length(trim(file_name)) between 1 and 255),
  media_type text not null check (media_type in ('image','video','thumbnail')),
  mime_type text not null,
  width integer check (width is null or width > 0),
  height integer check (height is null or height > 0),
  duration_seconds numeric(10,2) check (duration_seconds is null or duration_seconds >= 0),
  size_bytes bigint not null check (size_bytes > 0),
  alt_text text not null default '',
  uploaded_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.assignments (
  id uuid primary key default extensions.gen_random_uuid(),
  content_item_id uuid not null references public.content_items(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete restrict,
  assigned_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (content_item_id, profile_id)
);

create table public.review_comments (
  id uuid primary key default extensions.gen_random_uuid(),
  content_item_id uuid not null references public.content_items(id) on delete cascade,
  body text not null check (length(trim(body)) between 1 and 4000),
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.status_history (
  id uuid primary key default extensions.gen_random_uuid(),
  idea_id uuid references public.ideas(id) on delete cascade,
  content_item_id uuid references public.content_items(id) on delete cascade,
  from_status public.workflow_status,
  to_status public.workflow_status not null,
  note text not null default '',
  changed_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint exactly_one_history_target check ((idea_id is not null)::int + (content_item_id is not null)::int = 1)
);

create table public.share_events (
  id uuid primary key default extensions.gen_random_uuid(),
  content_item_id uuid not null references public.content_items(id) on delete cascade,
  event_type public.share_event_type not null,
  platform_id smallint references public.platforms(id) on delete set null,
  session_hash text,
  user_agent_family text,
  created_at timestamptz not null default now()
);

create index ideas_campaign_status_idx on public.ideas(campaign_id, status, updated_at desc);
